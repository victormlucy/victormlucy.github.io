const languageSelect = document.querySelector("[data-language-select]");
const languageStorageKey = "victormlucy-site-language";
let savedLanguage = "en";

try {
    const storedLanguage = localStorage.getItem(languageStorageKey);
    if (storedLanguage === "es" || storedLanguage === "fr") {
        savedLanguage = storedLanguage;
    }
} catch (error) {
    console.warn("Could not restore the saved site language.", error);
}

function applyLanguage(language) {
    const dictionary = translations[language] || {};
    document.documentElement.lang = language;

    document.querySelectorAll("[data-i18n]").forEach((element) => {
        if (!element.hasAttribute("data-i18n-default")) {
            element.setAttribute("data-i18n-default", element.textContent);
        }
        element.textContent = dictionary[element.dataset.i18n] ?? element.getAttribute("data-i18n-default");
    });

    [
        ["content", "data-i18n-content"],
        ["title", "data-i18n-title"],
        ["aria-label", "data-i18n-aria-label"],
        ["alt", "data-i18n-alt"]
    ].forEach(([attribute, selector]) => {
        document.querySelectorAll(`[${selector}]`).forEach((element) => {
            const defaultAttribute = `${selector}-default`;
            if (!element.hasAttribute(defaultAttribute)) {
                element.setAttribute(defaultAttribute, element.getAttribute(attribute));
            }
            const translation = dictionary[element.getAttribute(selector)];
            element.setAttribute(attribute, translation ?? element.getAttribute(defaultAttribute));
        });
    });

    if (languageSelect) {
        languageSelect.value = language;
    }
}

if (languageSelect) {
    languageSelect.addEventListener("change", () => {
        const language = languageSelect.value;
        applyLanguage(language);

        try {
            localStorage.setItem(languageStorageKey, language);
        } catch (error) {
            console.warn("Could not save the selected site language.", error);
        }
    });
}

applyLanguage(savedLanguage);
